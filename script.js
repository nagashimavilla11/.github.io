(() => {
 const languages=['ja','en','ko','zh-TW'];
 const dict=window.NV11_TRANSLATIONS||{};
 const originals=new WeakMap();
 let lang='ja';
 try { const saved=new URL(location.href).searchParams.get('lang')||localStorage.getItem('nv11-language'); if(languages.includes(saved))lang=saved; } catch {}
 const translate=key=>lang==='ja'?key:dict[key]?.[lang]||key;
 window.nv11Translate=translate;
 function convert(node,key,value,write){
   const trimmed=value.trim();
   let records=originals.get(node); if(!records){records={};originals.set(node,records);}
   let record=records[key];
   if(dict[trimmed] && (!record || value!==record.last)) record=records[key]={ja:trimmed,last:value};
   if(!record)return;
   const result=value.replace(trimmed,translate(record.ja));
   record.last=result;
   if(value!==result)write(result);
 }
 function scan(root){
   if(root.nodeType===Node.TEXT_NODE){
     if(!root.parentElement?.closest('script,style,select,iframe'))convert(root,'text',root.data,value=>root.data=value);
     return;
   }
   if(root.nodeType!==Node.ELEMENT_NODE && root!==document)return;
   if(root.nodeType===Node.ELEMENT_NODE){
     if(root.matches('script,style,select,iframe'))return;
     for(const attr of ['alt','title','aria-label','data-caption','content']){
       if(root.hasAttribute(attr))convert(root,attr,root.getAttribute(attr),value=>root.setAttribute(attr,value));
     }
   }
   root.childNodes.forEach(scan);
 }
 const selector=document.getElementById('site-language');
 const observer=new MutationObserver(records=>{
   for(const record of records){
     if(record.type==='childList')record.addedNodes.forEach(scan);
     else scan(record.target);
   }
 });
 function apply(){
   observer.disconnect();
   document.documentElement.lang=lang;
   selector.value=lang;
   scan(document);
   document.querySelectorAll('.booking-language-note').forEach(el=>el.hidden=lang==='ja');
   window.dispatchEvent(new CustomEvent('nv11-language-change'));
   observer.observe(document.documentElement,{subtree:true,childList:true,characterData:true,attributes:true,attributeFilter:['alt','title','aria-label','data-caption']});
 }
 selector.addEventListener('change',()=>{lang=selector.value;try{localStorage.setItem('nv11-language',lang);}catch{}apply();});
 apply();
})();
